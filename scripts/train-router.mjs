// Trains the Naive-Bayes intent model from labelled training sets -> src/app/core/tools/router-model.ts
//   node scripts/train-router.mjs count <file.md> <out.json>     (run per file, in parallel)
//   node scripts/train-router.mjs merge <counts.json...>         (writes router-model.ts)
import fs from 'node:fs'; import path from 'node:path'; import readline from 'node:readline'; import { build } from 'esbuild';
const root = path.resolve(import.meta.dirname, '..'); const [mode, ...args] = process.argv.slice(2);
const cats = JSON.parse(fs.readFileSync(path.join(root, 'training/categories.json'), 'utf8')); const CN = Object.keys(cats);
if (mode === 'count') {
  const out = path.join(process.env.TMPDIR || '/tmp', `router-nb-${process.pid}.mjs`);
  await build({ entryPoints: [path.join(root, 'src/app/core/tools/router-nb.ts')], bundle: true, format: 'esm', outfile: out, logLevel: 'silent' });
  const { featurize } = await import(out); const [file, dest] = args; const lf = file.replace(/\.md$/, '.labels');
  const labels = fs.readFileSync(lf, 'utf8').split('\n'); const counts = {}; let li = 0, n = 0;
  for await (const line of readline.createInterface({ input: fs.createReadStream(file) })) {
    const m = /^\d+\. (.*)$/.exec(line); if (!m) continue; const c = +labels[li++];
    if (li % 2) continue; n++; // every other line is plenty
    for (const f of new Set(featurize(m[1]))) (counts[f] ??= new Array(CN.length).fill(0))[c]++;
  }
  fs.writeFileSync(dest, JSON.stringify({ n, counts })); console.log(dest, n);
} else if (mode === 'merge') {
  const MINC = +(process.env.MIN_COUNT || 60), SPREAD = +(process.env.MIN_SPREAD || 1.2), A = 0.1; const tot = {};
  for (const f of args) { const { counts } = JSON.parse(fs.readFileSync(f, 'utf8')); for (const [k, v] of Object.entries(counts)) { const t = (tot[k] ??= new Array(CN.length).fill(0)); v.forEach((x, i) => t[i] += x); } }
  const keep = Object.entries(tot).filter(([, v]) => v.reduce((a, b) => a + b, 0) >= MINC);
  const classTot = CN.map((_, c) => keep.reduce((a, [, v]) => a + v[c], 0)); const V = keep.length; const rows = {};
  for (const [k, v] of keep) {
    const lp = v.map((x, c) => Math.log((x + A) / (classTot[c] + A * V)));
    if (Math.max(...lp) - Math.min(...lp) < SPREAD) continue; // uninformative
    rows[k] = lp.map(x => String.fromCharCode(33 + Math.max(0, Math.min(90, Math.round(-x * 2))))).join('');
  }
  fs.writeFileSync(path.join(root, 'src/app/core/tools/router-model.ts'),
    `// GENERATED by scripts/train-router.mjs — do not edit.\nexport const ROUTER_MODEL: { classes: string[]; groups: Record<string, string[]>; rows: Record<string, string> } = ${JSON.stringify({ classes: CN, groups: cats, rows })};\n`);
  console.log(Object.keys(rows).length, 'features kept of', Object.keys(tot).length, '->', (fs.statSync(path.join(root, 'src/app/core/tools/router-model.ts')).size / 1024).toFixed(0), 'KB');
}
