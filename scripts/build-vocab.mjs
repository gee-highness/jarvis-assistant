// Learns the vocabulary of how the user talks from training/*.md -> src/app/core/tools/vocab.ts (used for typo repair).
import fs from 'node:fs'; import path from 'node:path'; import readline from 'node:readline';
const root = path.resolve(import.meta.dirname, '..');
const files = (process.argv.slice(2).length ? process.argv.slice(2) : ['1', '2', '11', '12'].map(n => `training/jarvis_messages_${n}.md`)).map(f => path.resolve(root, f));
const MIN = +(process.env.MIN_FREQ || 120); const freq = new Map();
for (const f of files) for await (const line of readline.createInterface({ input: fs.createReadStream(f) })) {
  const m = /^\d+\. (.*)$/.exec(line); if (!m) continue;
  for (const w of m[1].toLowerCase().match(/[a-z']+/g) ?? []) freq.set(w, (freq.get(w) ?? 0) + 1);
}
const ts = fs.readFileSync(path.join(root, 'src/app/core/tools/tools.service.ts'), 'utf8');
for (const w of ts.slice(ts.indexOf('const TRIGGERS'), ts.indexOf('};', ts.indexOf('const TRIGGERS'))).toLowerCase().match(/[a-z]{4,}/g) ?? []) freq.set(w, Math.max(freq.get(w) ?? 0, MIN));
const words = [...freq].filter(([w, c]) => c >= MIN && w.length >= 2).map(([w]) => w).sort();
fs.writeFileSync(path.join(root, 'src/app/core/tools/vocab.ts'),
  `// GENERATED by scripts/build-vocab.mjs from training/*.md — do not edit.\nexport const VOCAB: ReadonlySet<string> = new Set(\n${JSON.stringify(words.join(' '))}.split(' '));\n`);
console.log(words.length, 'words');
